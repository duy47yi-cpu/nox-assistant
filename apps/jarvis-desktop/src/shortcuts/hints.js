function isSarcasticDirection(norm, match) {
  const hasMoreWord = Boolean(match && match[1]);
  if (IRONIC_STRONG_RE.test(norm)) return true;
  if (IRONIC_PRAISE_RE.test(norm) && hasMoreWord) return true;
  return false;
}

/**
 * Распознаёт бытовой намёк, полуслово или сарказм и строит локальный план действий.
 * Возвращает null, если сработала защита от ложных срабатываний или фраза не распознана.
 */
function resolveHint(text) {
  const raw = String(text || '').trim();
  const norm = normalizeHintText(raw);
  if (hasGuardrailBlock(raw, norm)) return null;

  for (const rule of DISCOMFORT_RULES) {
    if (rule.re.test(norm)) {
      return HINT_DEFS[rule.id]();
    }
  }

  for (const rule of DIRECTION_RULES) {
    const match = rule.re.exec(norm);
    if (match && isSarcasticDirection(norm, match)) {
      return HINT_DEFS[rule.flipped]();
    }
  }

  for (const rule of SOFT_REQUEST_RULES) {
    if (rule.re.test(norm)) {
      return HINT_DEFS[rule.id]();
    }
  }

  return null;
}

