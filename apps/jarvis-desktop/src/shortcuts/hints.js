'use strict';

// Разбор полуслов, бытовых намёков и очевидного сарказма.
// Возвращает готовый локальный план для сценариев или null, если фраза не про это.

const VOLUME_UP_KEYS = 'volume_up volume_up volume_up volume_up volume_up';
const VOLUME_DOWN_KEYS = 'volume_down volume_down volume_down volume_down volume_down';

const MAX_HINT_CHARS = 200;
const MAX_HINT_WORDS = 20;

// Вопросительные зачины: не мешаем обычным вопросам к помощнику, но пропускаем «что-то/как-то/какая-нибудь».
const LEADING_QUESTION_RE = /^(?:почему|зачем|откуда|куда|кто|кого|кому|кем|чего|чем|можно\s+ли|стоит\s+ли|правда\s+ли|объясни|обьясни|расскажи|подскажи|когда|сколько|какой(?!-то|-нибудь|-либо)|какие(?!-то|-нибудь|-либо)|как(?!-то)|какая(?!-то|-нибудь|-либо)|что(?!-то|-нибудь|-либо|\s+(?:то|нибудь|либо)))(?=$|[^a-zа-я0-9])/i;

// Прямые запреты действия и отрицания признака; не задевают «ничего не слышно / не видно».
const NEGATION_RE = /(?:^|[^a-zа-я0-9])(?:не\s+(?:надо|нужно|делай|трогай|трожь|стоит|хочу|меняй|крути|ставь|включай|громко|громче|тихо|тише|ярко|ярче|темно|темнее|орет|кричит|слепит|режет)|(?:громче|тише|ярче|темнее|звук|яркость|окна)\s+не\s+(?:надо|нужно|делай|трогай|меняй)|хватит|прекрати|остановись)(?=$|[^a-zа-я0-9])/i;

// Внешняя обстановка, погода, бытовые приборы вне экрана и звука ПК.
const EXTERNAL_PLACE_RE = /(?:^|[^a-zа-я0-9])(?:в\s+комнате|на\s+улице|в\s+подъезде|в\s+коридоре|дома|на\s+кухне|в\s+офисе|за\s+окном|в\s+метро|в\s+автобусе|в\s+машине|в\s+зале|на\s+дворе|на\s+небе|в\s+лесу|погод[аеу]|люстр[аеу]|ламп[аеу]|фонар[ьеа]?)(?=$|[^a-zа-я0-9])/i;

// Разговоры про третьих лиц и соседей.
const THIRD_PERSON_RE = /(?:^|[^a-zа-я0-9])(?:у\s+сосед[а-я]*|сосед[а-я]*|у\s+друг[а-я]*|коллег[а-я]*|начальник[а-я]*|мам[аеу]|пап[аеу]|жен[аеу]|муж|ребен[а-я]*|дети|детей|кот|собак[а-я]*|(?:он|она|они)\s+(?:орет|орут|кричит|кричат|молчит|молчат|спит|спят|говорит|говорят))(?=$|[^a-zа-я0-9])/i;

// Устойчивые обороты и термины интерфейса, не являющиеся жалобой на звук/экран/окна.
const IDIOM_OR_UI_RE = /(?:^|[^a-zа-я0-9])(?:громко\s+сказано|тихий\s+океан|тихий\s+дон|тихий\s+час|тихий\s+ужас|в\s+тихом\s+омуте|тише\s+едешь|темн(?:ая|ой|ую)\s+тем[аеу]|темн(?:ый|ом)\s+режим|темно-|ярко-|яркий\s+пример|яркая\s+личность|яркое\s+впечатление|бардак\s+(?:на\s+столе|в\s+жизни|в\s+голове|в\s+коде|в\s+комнате|в\s+квартире))(?=$|[^a-zа-я0-9])/i;

// Опасные слова никогда не разрешаем через намёки.
const DANGER_RE = /(?:^|[^a-zа-я0-9])(?:удал[иь]|выключи\s+комп|перезагруз|форматир|парол|оплат|перевед[иь]\s+деньг)(?=$|[^a-zа-я0-9])/i;

// Маркеры иронии для переворота полярности у императивов («ну да, сделай ещё тише»).
const IRONIC_STRONG_RE = /(?:^|[^a-zа-я0-9])(?:ну\s+да|ага|конечно|браво|молодец|обожаю|давай\s+еще|ну\s+давай)(?=$|[^a-zа-я0-9])/i;
const IRONIC_PRAISE_RE = /(?:^|[^a-zа-я0-9])(?:класс(?:но)?|супер|спасибо(?:\s+большое)?|отлично|шикарно|великолепно|кайф|прекрасно|замечательно|чудесно|идеально)(?=$|[^a-zа-я0-9])/i;

function normalizeHintText(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[«»"'`]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function cyr(pattern) {
  return new RegExp(`(?:^|[^a-zа-я0-9])(?:${pattern})(?=$|[^a-zа-я0-9])`, 'i');
}

function hasGuardrailBlock(raw, norm) {
  if (!raw || !norm) return true;
  if (raw.length > MAX_HINT_CHARS) return true;
  if (norm.split(/\s+/).filter(Boolean).length > MAX_HINT_WORDS) return true;
  if (raw.includes('?')) return true;
  if (LEADING_QUESTION_RE.test(norm)) return true;
  if (NEGATION_RE.test(norm)) return true;
  if (EXTERNAL_PLACE_RE.test(norm)) return true;
  if (THIRD_PERSON_RE.test(norm)) return true;
  if (IDIOM_OR_UI_RE.test(norm)) return true;
  if (DANGER_RE.test(norm)) return true;
  return false;
}

function makePlan(id, title, steps, summaryReply) {
  return {
    kind: 'command',
    isSequence: steps.length > 1,
    source: 'hint',
    hintId: id,
    title,
    name: title,
    ownerCommand: false,
    parts: [{ title, source: 'hint', steps: steps.map((s) => ({ tool: s.tool, args: { ...(s.args || {}) } })) }],
    steps,
    notes: [],
    summaryReply,
  };
}

