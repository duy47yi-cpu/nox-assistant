'use strict';

// Просьбы о списке программ и о наблюдении за ними. Без модели.
// Список читается сам, один раз, без вопросов (решение владельца 31.10.2026), поэтому здесь только фразы.

// Просьба просканировать программы явно: сделать сейчас, не дожидаясь раза в сутки.
const SCAN_REQUEST = /(просканируй|сканируй|обнови|проверь|посмотри).*(программ|приложени|установлен)|(какие|что)\s+(у меня\s+)?(стоят?|установлен).*(программ|приложени)/i;
// Просьба забыть список и историю использования.
// «удали» не берём: удаление программ обрабатывает политика, а не эта фраза.
const FORGET_REQUEST = /(забудь|сотри|сбрось).*(список программ|список приложений|программ|приложений)/i;

function isScanRequest(text) {
  return SCAN_REQUEST.test(String(text || ''));
}

function isForgetRequest(text) {
  return FORGET_REQUEST.test(String(text || ''));
}

module.exports = { isScanRequest, isForgetRequest };
