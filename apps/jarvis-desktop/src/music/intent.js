'use strict';

// Музыкальные команды без модели: распознать просьбу, спросить сервис один раз, открыть поиск.
// Сервисы и адреса поиска. Адрес собирается только из кодированного запроса.
const SERVICES = {
  youtube: { title: 'YouTube', url: (q) => `https://www.youtube.com/results?search_query=${encodeURIComponent(q)}` },
  youtube_music: { title: 'YouTube Music', url: (q) => `https://music.youtube.com/search?q=${encodeURIComponent(q)}` },
  yandex: { title: 'Яндекс Музыка', url: (q) => `https://music.yandex.ru/search?text=${encodeURIComponent(q)}` },
  spotify: { title: 'Spotify', url: (q) => `https://open.spotify.com/search/${encodeURIComponent(q)}` },
};

const MUSIC_WORD = /(музык|песн|трек|мелоди|альбом|плейлист|послуш|клип|исполнител)/i;
const PLAY_WORD = /(постав[ьи]т?ь?|включ[иа]ть?|сыгра[йт]|играй|запуст[иа]ть?|открой|открыть|хочу|найди|найти)/i;
// «Поставь …», «врубай …», «сыграй …» без слова «музыка» почти всегда про музыку. «Включи» не берём: это и свет, и экран.
const MUSIC_START = /^\s*(постав[ьи]|врубай|врубите|сыграй|сыграйте)\s+\S/i;
// Даже если фраза начинается с «поставь», это не музыка: настройки ПК, сценарии, проекты.
const NOT_MUSIC = /(громкост|экран|монитор|окн|сценари|протокол|команд|напоминан|таймер|будильник|уведомлен|фокус|презентац|проект|клод|claude)/i;

// Слова-пустышки убираем из запроса: остаётся то, что искать, например «мияги» или «спокойная».
const FILLER = new Set([
  'поставь', 'поставить', 'постави', 'включи', 'включить', 'сыграй', 'играй', 'запусти', 'открой', 'открыть', 'найди', 'найти', 'хочу', 'ты', 'ничего', 'не', 'открыл', 'я', 'просил', 'просила',
  'музыку', 'музыка', 'музыки', 'песню', 'песня', 'песни', 'трек', 'мелодию', 'мелодия', 'альбом',
  'любую', 'любой', 'любое', 'любимую', 'что-нибудь', 'что', 'нибудь', 'какую-нибудь', 'какой-нибудь',
  'короче', 'давай', 'просто', 'ну', 'вот', 'сейчас', 'тогда', 'можешь', 'можно', 'пусть', 'мне', 'пожалуйста', 'там', 'здесь',
  'ладно', 'окей', 'ок', 'хорошо', 'да', 'ага',
  'ставь', 'ставьте', 'ставить', 'ставит', 'согласен', 'согласна', 'согласны', 'согласись',
  'название', 'названия', 'называется', 'назови', 'типа', 'названием', 'помню', 'её', 'ее', 'это',
  // Команды к кнопке и уточнения: «нажми на play», «именно то, что я хотел» — не название песни.
  'привет', 'приветик', 'здарова', 'хай', 'добрый', 'день', 'вечер', 'утро',
  'нажми', 'нажать', 'жми', 'плей', 'плэй', 'play', 'именно', 'хотел', 'хотела', 'хотелось', 'еще', 'ещё', 'заново',
  'слушай', 'ахах', 'ахахах', 'та', 'тот', 'то', 'ту', 'так', 'было', 'раньше', 'помнишь', 'опять', 'снова',
  'джарвис', 'джарвису', 'в', 'на', 'от', 'с', 'и', 'ютуб', 'ютубе', 'ютуб-музыку', 'youtube',
  'яндекс', 'яндекса', 'спотифай', 'spotify',
  // Разговорные слова из просьб вроде «я щас в тиктоке была песня ты как закаты…».
  'тиктоке', 'тикток', 'тиктока', 'щас', 'ща', 'была', 'был', 'как', 'послушаю', 'послушать', 'песенку', 'песенка', 'будет', 'хочу', 'любовная', 'любовной',
  'прокрути', 'перемотай', 'промотай', 'начни',
  // Связки между делами: «поставь мияги, а потом …» — хвост дела вырезает stripOtherDeals, связка остаётся.
  'а', 'потом', 'затем', 'после', 'этого', 'врубай', 'врубите', 'сыграйте',
]);

// Другое дело в той же просьбе: вопрос, погода, время, курс, таймер, напоминание, «проверь/скажи/покажи/сколько».
// Ни одно из этих слов не название песни, когда рядом есть «поставь/включи».
const DEAL_WORDS = [
  'провер[а-яё]*', 'скажи(?:те)?', 'подскажи(?:те)?', 'расскажи(?:те)?', 'покажи(?:те)?', 'узнай(?:те)?', 'посмотри(?:те)?', 'глянь',
  'сколько', 'погод[а-яё]*', 'температур[а-яё]*', 'прогноз[а-яё]*', 'градус[а-яё]*', 'который\\s+час', 'курс[а-яё]*', 'доллар[а-яё]*', 'евро',
  'таймер[а-яё]*', 'будильник[а-яё]*', 'напомн[а-яё]*', 'напоминани[а-яё]*', 'новост[а-яё]*',
  'какая', 'какой', 'какое', 'какие', 'когда', 'где', 'почему', 'зачем', 'что\\s+(?:такое|там|нового|по|с|у)',
].join('|');
// «открой калькулятор», но не «открой ютуб и поставь» и не «открой её».
const OPEN_OTHER = 'откр[а-яё]*\\s+(?!(?:мне\\s+)?(?:ютуб|youtube|яндекс|спотиф|spotify|музык|песн|трек|видео|клип|е[её](?=[\\s,.!?]|$)|его(?=[\\s,.!?]|$)|там(?=[\\s,.!?]|$)))';
const DEAL_START = `(^|[\\s,.;:!?«"(])(?:(?:${DEAL_WORDS})(?=[\\s,.;:!?»")]|$)|${OPEN_OTHER})`;
const DEAL_RE = new RegExp(DEAL_START, 'i');
// Дело тянется до следующей музыкальной команды («… и поставь мияги») или до конца фразы.
const DEAL_CLAUSE_RE = new RegExp(`${DEAL_START}[\\s\\S]*?(?=[\\s,.;:!?]+(?:(?:и|а|потом|затем)\\s+)?(?:постав|включ|сыгра|врубай|играй|найди)[а-яё]*|$)`, 'gi');

// Убрать из запроса чужие дела: «мияги бадабум проверить погоду» → «мияги бадабум».
// Если вырезалось всё, а слова «музыка/песня» нет («погода в доме», «когда ты рядом») — это название, оставляем как было.
function stripOtherDeals(text) {
  const raw = String(text || '');
  const cut = raw.replace(DEAL_CLAUSE_RE, '$1').replace(/\s+/g, ' ').trim();
  return queryWords(cut).length || MUSIC_WORD.test(cut) ? cut : raw.trim();
}

// Время старта: «до 16 секунд», «с 16 секунды», «на 16-й секунде». \b не работает с кириллицей — границы через пробел.
const START_RE = /(^|\s)(до|со?|на)\s+(\d{1,5})(?:-?[а-яё]{1,2})?\s*сек[а-яё]*(?=[\s.,!?]|$)/i;

// Секунда, с которой включить видео, или null.
function parseStartSeconds(text) {
  const m = START_RE.exec(String(text || ''));
  if (!m) return null;
  const s = Number(m[3]);
  return s > 0 ? s : null;
}

// После музыки в той же просьбе есть другое действие («… и закрой все окна», «… проверь погоду», вопрос):
// такую просьбу ведёт модель по шагам, музыка и ответ выполняются оба.
const OTHER_STEP_RE = /(^|\s)(и|потом|затем|после этого)\s+(закр|сверн|выключ|удал|напиш|отправ|сохран|перезагруз|разлож)[а-яё]*/i;
function hasOtherSteps(text) {
  const t = String(text || '');
  return OTHER_STEP_RE.test(t) || DEAL_RE.test(t) || t.includes('?');
}

// Есть ли в тексте музыкальная просьба (играть/включить + музыка, или «поставь/врубай + название»).
function isMusicRequest(text) {
  const t = String(text || '');
  if (MUSIC_WORD.test(t) && PLAY_WORD.test(t)) return true;
  return MUSIC_START.test(t) && !NOT_MUSIC.test(t);
}

// Сервис, который назвал владелец в ответе на вопрос. null, если не распознан.
function parseService(text) {
  const t = String(text || '').toLowerCase();
  if (/ютуб.*музык|youtube\s*music|music\.youtube/.test(t)) return 'youtube_music';
  if (/ютуб|youtube/.test(t)) return 'youtube';
  if (/яндекс/.test(t)) return 'yandex';
  if (/spotify|спотифай|спотик/.test(t)) return 'spotify';
  return null;
}

// Слова запроса без слов-пустышек. Пусто — значит владелец не назвал ни исполнителя, ни трек.
function queryWords(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[?!.,;:«»"()]/g, ' ')
    .split(/\s+/)
    // «музика», «музыкe» и другие опечатки слова «музыка» — тоже пустышки.
    .filter((w) => w && !FILLER.has(w) && !/^муз[ыи]к/.test(w));
}

// Поисковый запрос: текст без слов-пустышек. Если ничего не осталось — общий запрос.
function cleanQuery(text) {
  // Длительность («на час», «на 30 минут») не входит в название: в поиск её не отправляем.
  // \b в JS не работает с кириллицей, поэтому границы слов — через пробел и конец строки.
  const withoutDuration = stripOtherDeals(text)
    .replace(/(^|\s)на\s+(полчаса|час[а-я]*|\d+\s*(час[а-я]*|минут[а-я]*|мин))(?=\s|$)/gi, ' ')
    .replace(new RegExp(START_RE.source, 'gi'), ' ');
  return queryWords(withoutDuration).join(' ') || 'музыка';
}

// Есть ли в просьбе слово «играть» (поставь, включи, сыграй…).
function hasPlayWord(text) {
  return PLAY_WORD.test(String(text || ''));
}

// Ссылка на ранее сыгранное: «та самая самая», «поставь ту песню мияги» — нужны слова из прошлого запроса
// и маркер ссылки. entries — сыгранные запросы, новые сначала. null, если ничего не подходит.
const REFERENCE_RE = /(^|\s)(та|тот|то|ту|те|той|эта|эту|раньше|помнишь|прошлую|предыдущую|опять|снова)(\s|$)/i;
function matchHistory(text, entries) {
  const raw = String(text || '');
  if (!REFERENCE_RE.test(raw)) return null;
  const words = new Set(queryWords(raw));
  for (const e of Array.isArray(entries) ? entries : []) {
    const qw = queryWords(e && e.query);
    if (qw.length && e.query !== 'музыка' && qw.every((w) => words.has(w))) return { ...e, query: qw.join(' ') };
  }
  return null;
}

// «Поставь ещё такую же», «похожую» — без своих слов: берём последний сыгранный запрос (entries[0]).
const SIMILAR_RE = /(^|\s)(такую|такой|такое|такие|такого|похожую|похожая|похожий|похожее|похожие)(\s|$)/i;
const SIMILAR_WORDS = new Set(['такую', 'такой', 'такое', 'такие', 'такого', 'похожую', 'похожая', 'похожий', 'похожее', 'похожие', 'же']);
function repeatLast(text, entries) {
  const raw = String(text || '');
  if (!SIMILAR_RE.test(raw) || !hasPlayWord(raw) || !queryWords(raw).every((w) => SIMILAR_WORDS.has(w))) return null;
  const last = Array.isArray(entries) ? entries[0] : null;
  return last ? { service: last.service, query: last.query } : {};
}

// «Поставь её», «включи это» — повтор последней музыкальной просьбы без названия.
function isPronounPlay(text) {
  const t = String(text || '').toLowerCase().replace(/[.!?,]/g, ' ').replace(/\s+/g, ' ').trim();
  return /^(ладно |ну |окей |ок |да )?(постав[а-яё]*|включ[а-яё]*|сыгра[а-яё]*|запусти[а-яё]*) (её|ее|его|это|эту|этот|ту|ещё|еще)$/.test(t);
}

// Просьба сменить сервис: «смени музыкальный сервис», «сбрось сервис музыки».
function isResetServiceRequest(text) {
  return /(смени|сменить|сбрось|сбросить|другой|поменяй|поменять).*(сервис|музык)/i.test(String(text || ''));
}

module.exports = {
  SERVICES, isMusicRequest, parseService, cleanQuery, isResetServiceRequest, isPronounPlay,
  queryWords, hasPlayWord, matchHistory, repeatLast, parseStartSeconds, hasOtherSteps, stripOtherDeals,
};
