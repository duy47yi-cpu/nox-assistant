'use strict';

// Оформление ответа в чате: выбирается в Настройках (replyStyle), дописывается к правилам модели.
// plain — как было: коротко, без оформления. Окно рисует жирный, списки и формулы при любом стиле.

const STYLES = Object.freeze({
  plain: { title: 'Простой', note: '' },
  rich: {
    title: 'Выразительный',
    note: [
      'Оформление ответа «Выразительный» (важнее правила о коротких ответах без заголовков).',
      'Разговорную реплику и отчёт о выполненном действии оставляй одной-двумя фразами, без оформления.',
      'Объяснение, расчёт, сравнение или справку оформляй так:',
      '- первая строка — прямой ответ на вопрос;',
      '- дальше смысловые блоки, у каждого подпись жирным отдельной строкой, например «**Сравнение масс:**»;',
      '- ключевые числа и выводы выделяй **жирным**, но не больше двух-трёх выделений на абзац;',
      '- формулы и расчёты пиши в LaTeX: внутри строки $...$, отдельной строкой $$...$$. Понимаются \\frac, \\sqrt, степени ^, индексы _, \\approx, \\times, \\cdot, \\text{} и греческие буквы. Деньги пиши словом «долларов», без знака $;',
      '- оговорку или уточнение ставь в конец отдельной строкой, начиная с «* ».',
      'Таблицы и заголовки с # не используй.',
    ].join('\n'),
  },
  notes: {
    title: 'Конспект',
    note: [
      'Оформление ответа «Конспект» (важнее правила о коротких ответах без заголовков).',
      'Разговорную реплику и отчёт о выполненном действии оставляй одной-двумя фразами, без оформления.',
      'Объяснение или справку давай конспектом: строка-название жирным, под ней маркированный список из коротких пунктов (до семи, каждый — одна мысль, главное слово жирным), в конце строка «**Итог:** …».',
      'Формулы пиши в LaTeX: внутри строки $...$, отдельной строкой $$...$$. Таблицы и заголовки с # не используй.',
    ].join('\n'),
  },
});

const styleId = (id) => (Object.prototype.hasOwnProperty.call(STYLES, id) ? id : 'plain');
const replyStyleNote = (id) => STYLES[styleId(id)].note;

// Текст для голоса: без разметки; формулы вслух не читаются.
function forSpeech(text) {
  return String(text || '')
    .replace(/\$\$[\s\S]*?\$\$|\\\[[\s\S]*?\\\]|\\\([\s\S]*?\\\)|\$(?=\S)[^$\n]*[\\^_=][^$\n]*\$/g, ' формула ')
    .replace(/\*\*|`/g, '')
    .replace(/^\s*\*\s+/gm, '')
    .replace(/[ \t]{2,}/g, ' ')
    .trim();
}

module.exports = { STYLES, styleId, replyStyleNote, forSpeech };
